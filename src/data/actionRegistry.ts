export function getActionsByIsland(islandId: PageId): ActionDefinition[] {
  return ACTION_REGISTRY.filter((a) => a.islandId === islandId);
}

export function getActionsByMode(islandId: PageId, mode: 'M' | 'W' | 'E'): ActionDefinition[] {
  return ACTION_REGISTRY.filter((a) => a.islandId === islandId && a.mode === mode);
}

export function getJobActionsByCategory(category: 'definition' | 'run'): ActionDefinition[] {
  return ACTION_REGISTRY.filter((a) => a.islandId === 'jobs-processes' && a.jobCategory === category);
}

export function getActionByCode(actionCode: string): ActionDefinition | undefined {
  return ACTION_REGISTRY.find((a) => a.actionCode === actionCode);
}
